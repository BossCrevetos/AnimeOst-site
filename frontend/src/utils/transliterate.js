// Функция для простой транслитерации японских символов
export const transliterateJapanese = (text) => {
  if (!text) return '';
  
  let result = '';
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const nextChar = text[i + 1];
    
    // Пропускаем английские буквы и цифры
    if (/[a-zA-Z0-9]/.test(char)) {
      result += char.toLowerCase();
      continue;
    }
    
    // Пробуем найти в словаре
    if (kanaToRomaji[char]) {
      // Обработка удвоенных согласных (маленькое っ/ッ)
      if ((char === 'っ' || char === 'ッ') && nextChar && kanaToRomaji[nextChar]) {
        const nextRomaji = kanaToRomaji[nextChar];
        if (nextRomaji && nextRomaji[0]) {
          result += nextRomaji[0]; // Удваиваем первую букву следующего слога
        }
        continue;
      }
      
      result += kanaToRomaji[char];
    } else {
      // Если символ не в словаре, оставляем как есть
      result += char.toLowerCase();
    }
  }
  
  return result;
};

// Функция для нормализации текста для поиска
export const normalizeForSearch = (text) => {
  if (!text) return '';
  
  // Приводим к нижнему регистру
  const lowerText = text.toLowerCase();
  
  // Транслитерируем японские символы
  const transliterated = transliterateJapanese(lowerText);
  
  // Убираем лишние символы
  return transliterated.replace(/[^\w\s]/g, '');
};